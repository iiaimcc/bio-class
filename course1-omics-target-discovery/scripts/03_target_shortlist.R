#!/usr/bin/env Rscript
# =============================================================================
# 03_target_shortlist.R
# Course: "Omics-based disease mechanism dissection and target discovery" (Part 3)
#
# What this script does:
#   1. Reads the DEG table from step 1, the curated druggable panel and the
#      mutation matrix built from the same TCGA-LUAD samples
#   2. Intersects DEGs with the panel -> expression-driven candidates
#   3. Lists mutated driver genes -> mutation-driven candidates
#   4. Applies the biology-only funnel (variant present -> protein switched on
#      -> reachable by the large molecule we design in course 3) -> writes
#      integrated_candidates.csv and target_recommendation.csv
#      Layer 2 uses the MAF for truncating variants and variant_calls.csv
#      (student-filled, from ClinVar / CIViC) for the rest
#      Layer 3 uses target_context.csv (generated by data/annotate_targets.py)
#   5. Prints the evidence for EGFR, which is the last one standing
#
# How to run:
#   Rscript 03_target_shortlist.R  <data_dir>  <out_dir>
# =============================================================================

# ---- 0. Configuration --------------------------------------------------------
args <- commandArgs(trailingOnly = TRUE)
data_dir <- if (length(args) >= 1) args[1] else "."
out_dir  <- if (length(args) >= 2) args[2] else "./results"
dir.create(out_dir, showWarnings = FALSE, recursive = TRUE)

for (p in c("dplyr", "readr", "tidyr")) {
  if (!requireNamespace(p, quietly = TRUE)) stop("Package '", p, "' missing")
}
suppressPackageStartupMessages({ library(dplyr); library(readr); library(tidyr) })

# ---- 1. Load inputs ------------------------------------------------------------
deg_file <- file.path(out_dir, "deg_table_all.csv")
if (!file.exists(deg_file))
  stop("Missing ", deg_file, " - run 01_diff_analysis.R first (same <out_dir>)")
panel_file <- file.path(data_dir, "druggable_panel.csv")
if (!file.exists(panel_file))
  stop("Missing ", panel_file, " - pass the course1 data dir as the first argument")
mut_file <- file.path(data_dir, "mutation_matrix.csv")
if (!file.exists(mut_file))
  stop("Missing ", mut_file, " - run data/fetch_tcga_luad.py or use the fallback copy")

deg   <- read_csv(deg_file, show_col_types = FALSE)
panel <- read_csv(panel_file, show_col_types = FALSE)
mut   <- read_csv(mut_file, show_col_types = FALSE)
variants <- read_csv(file.path(data_dir, "mutation_status.csv"), show_col_types = FALSE)
cat("Deg table:", nrow(deg), "| druggable panel:", nrow(panel),
    "genes | tumours with mutation calls:", nrow(mut), "\n")

# Mutation counts per gene (mut is one row per tumour, 0/1 per gene)
mut_long <- mut %>%
  pivot_longer(-sample_id, names_to = "symbol", values_to = "mutated") %>%
  filter(mutated == 1) %>%
  count(symbol, name = "n_mutated")
examples <- variants %>%
  group_by(gene) %>%
  summarise(mutation_examples = paste(unique(hgvsp), collapse = "; "), .groups = "drop") %>%
  rename(symbol = gene)

# ---- 2. Significant DEGs --------------------------------------------------------
sig <- deg %>% filter(padj < 0.05, abs(log2FoldChange) > 1)
cat("Significant DEGs:", nrow(sig), "\n")

# ---- 3. Expression-driven candidates: DEGs that are druggable -------------------
candidates <- inner_join(sig, panel, by = "symbol") %>%
  left_join(mut_long, by = "symbol") %>%
  left_join(examples, by = "symbol") %>%
  mutate(n_mutated = coalesce(n_mutated, 0L),
         mutation_examples = coalesce(mutation_examples, "")) %>%
  arrange(desc(log2FoldChange)) %>%
  mutate(rank = row_number()) %>%
  select(rank, symbol, panel_class, known_drug_class, log2FoldChange, padj,
         baseMean, n_mutated, mutation_examples)

write_csv(candidates, file.path(out_dir, "target_shortlist.csv"))
cat("Saved target_shortlist.csv:", nrow(candidates), "expression-driven candidates\n")

# ---- 4. Mutation-driven candidates ---------------------------------------------
# A gene is listed if at least one tumour carries a non-silent variant. Absence
# of a call is not proof of wild type: one tumour has no MAF file, and MAF data
# cannot capture fusions or copy-number events.
mut_candidates <- mut_long %>%
  left_join(examples, by = "symbol") %>%
  left_join(deg %>% select(symbol, log2FoldChange, padj, baseMean),
            by = "symbol") %>%
  mutate(deg_status = case_when(
    is.na(padj)                              ~ "not tested (filtered out)",
    padj < 0.05 & abs(log2FoldChange) > 1    ~ "DEG",
    padj < 0.05                              ~ "padj<0.05 but |log2FC|<1",
    TRUE                                     ~ "not significant"
  )) %>%
  arrange(desc(n_mutated), desc(log2FoldChange)) %>%
  select(symbol, n_mutated, mutation_examples, deg_status,
         log2FoldChange, padj, baseMean)

write_csv(mut_candidates, file.path(out_dir, "mutation_driven_candidates.csv"))
cat("Saved mutation_driven_candidates.csv:", nrow(mut_candidates), "mutated genes\n")

# ---- 5. Biology-only evidence layers -------------------------------------------
# The funnel deliberately uses ONLY properties of the tumour and of the molecule:
# does this gene carry a non-silent variant in this cohort, does that variant
# switch the protein ON (gain of function), and is the protein somewhere a large
# molecule can reach it. Drug-landscape facts (does an approved drug already
# exist, is the gene in the druggable panel) are NOT filters: using them would
# rebuild the answer we already know and call it a discovery. They are printed
# afterwards, as precedent, in section 6.
#
# Layer 2 works at the variant level and only then rolls up to the gene, because
# one gene can carry several variants with different consequences (TP53 here has
# a nonsense variant in one tumour and DNA-binding-domain missense variants in
# others). Truncating variants are settled by the MAF itself - a destroyed
# protein cannot be switched on - and are auto-called. Splice-site, start-codon
# and nonstop variants are deliberately NOT auto-called: their effect depends on
# transcript and frame, or is not a truncation at all. Every other variant is
# looked up by the student in ClinVar / CIViC (helper: data/lookup_variant.py)
# and recorded in variant_calls.csv, one row per variant.
calls_file <- if (length(args) >= 3) args[3] else file.path(out_dir, "variant_calls.csv")
if (!file.exists(calls_file))
  stop("Missing ", calls_file, " - run data/make_variant_template.py, fill the ",
       "needs_review rows (see materials/templates/README.md), and save the table there")
calls <- read_csv(calls_file, show_col_types = FALSE)
required <- c("symbol", "sample_id", "hgvsp", "variant_class",
              "functional_consequence", "evidence_level", "evidence_source")
if (!all(required %in% names(calls)))
  stop("variant_calls.csv must have the columns: ", paste(required, collapse = ", "))

calls <- calls %>% mutate(functional_consequence = tolower(functional_consequence))
unresolved <- calls %>% filter(!functional_consequence %in%
                                 c("gain_of_function", "loss_of_function", "uncertain"))
if (nrow(unresolved))
  stop("Unresolved calls in ", calls_file, ": ",
       paste(unique(paste(unresolved$symbol, unresolved$hgvsp)), collapse = ", "),
       " - look them up and replace needs_review with gain_of_function / loss_of_function / uncertain")

# Match on the full record key: the same variant can recur in several patients
# (KRAS p.G12C and p.G12V do here), so symbol+hgvsp alone would let a partially
# filled table pass the check.
observed <- variants %>%
  distinct(symbol = gene, sample_id, hgvsp, variant_class) %>%
  mutate(hgvsp = coalesce(hgvsp, ""))
call_keys <- calls %>% distinct(symbol, sample_id, hgvsp, variant_class)
missing_rows <- anti_join(observed, call_keys, by = c("symbol", "sample_id", "hgvsp", "variant_class"))
if (nrow(missing_rows))
  stop("variant_calls.csv has no row for: ",
       paste(missing_rows$symbol, missing_rows$sample_id, missing_rows$hgvsp, sep = " / ", collapse = "; "))

extra_rows <- anti_join(call_keys, observed, by = c("symbol", "sample_id", "hgvsp", "variant_class"))
if (nrow(extra_rows))
  stop("variant_calls.csv has rows that are not in mutation_status.csv: ",
       paste(extra_rows$symbol, extra_rows$sample_id, extra_rows$hgvsp, sep = " / ", collapse = "; "))

dup_rows <- calls %>%
  count(symbol, sample_id, hgvsp, variant_class) %>%
  filter(n > 1)
if (nrow(dup_rows))
  stop("variant_calls.csv has duplicate rows for the same record: ",
       paste(dup_rows$symbol, dup_rows$sample_id, dup_rows$hgvsp, sep = " / ", collapse = "; "))

write_csv(calls, file.path(out_dir, "variant_function_summary.csv"))
cat("Saved variant_function_summary.csv:", nrow(calls), "variant-level calls (",
    sum(calls$functional_consequence == "gain_of_function"), "gain of function,",
    sum(calls$functional_consequence == "loss_of_function"), "loss of function,",
    sum(calls$functional_consequence == "uncertain"), "uncertain )\n")

# Roll the variant calls up to the gene. A gene with gain-of-function evidence
# AND loss-of-function evidence is reported as mixed rather than silently
# resolved: the two point in opposite directions and the decision belongs in the
# discussion, not in a default.
call_summary <- calls %>%
  group_by(symbol) %>%
  summarise(n_variants = n(),
            n_gof = sum(functional_consequence == "gain_of_function"),
            n_lof = sum(functional_consequence == "loss_of_function"),
            n_uncertain = sum(functional_consequence == "uncertain"),
            variant_function = case_when(
              n_gof > 0 & n_lof > 0 ~ "mixed (gain and loss of function calls)",
              n_gof > 0 ~ "gain_of_function",
              n_lof > 0 ~ "loss_of_function",
              TRUE ~ "uncertain"),
            evidence_level = paste(sort(unique(evidence_level)), collapse = " / "),
            variant_source = paste(sort(unique(evidence_source)), collapse = " ; "),
            .groups = "drop")

context_file <- file.path(data_dir, "target_context.csv")
if (!file.exists(context_file))
  stop("Missing ", context_file, " - run data/annotate_targets.py, or use the fallback copy")
context <- read_csv(context_file, show_col_types = FALSE)
precedent_file <- file.path(data_dir, "drug_precedent.csv")
if (!file.exists(precedent_file))
  stop("Missing ", precedent_file, " - pass the course1 data dir as the first argument")
precedent <- read_csv(precedent_file, show_col_types = FALSE)

integrated <- mut_candidates %>%
  left_join(call_summary, by = "symbol") %>%
  left_join(context %>% select(symbol, uniprot_accession, subcellular_location,
                               has_extracellular_domain), by = "symbol") %>%
  left_join(panel %>% select(symbol, known_drug_class), by = "symbol") %>%
  mutate(variant_function = coalesce(variant_function, "uncertain"),
         evidence_level = coalesce(evidence_level, "not looked up"),
         has_extracellular_domain = coalesce(has_extracellular_domain, "no"),
         on_druggable_panel = !is.na(known_drug_class),
         gain_of_function = variant_function == "gain_of_function",
         reachable_by_large_molecule = has_extracellular_domain == "yes") %>%
  arrange(desc(n_mutated), desc(gain_of_function), desc(log2FoldChange))

mixed_genes <- integrated %>% filter(grepl("^mixed", variant_function))
if (nrow(mixed_genes))
  cat("Note: mixed calls, review before use:", paste(mixed_genes$symbol, collapse = ", "), "\n")

# Layer 3 encodes the modality we chose for course 3 (a designed mini-protein /
# antibody-like binder), not a statement about target quality: an intracellular
# protein is a perfectly good target if you are building a small molecule.
final <- integrated %>%
  filter(gain_of_function, reachable_by_large_molecule) %>%
  mutate(rank = row_number()) %>%
  select(rank, symbol, variant_function, evidence_level, n_mutated, n_variants,
         n_gof, n_lof, n_uncertain, mutation_examples,
         subcellular_location, deg_status, log2FoldChange, padj, baseMean,
         known_drug_class, variant_source)
write_csv(integrated, file.path(out_dir, "integrated_candidates.csv"))
cat("Saved integrated_candidates.csv:", nrow(integrated),
    "mutated genes with variant-function and UniProt location annotation\n")
write_csv(final, file.path(out_dir, "target_recommendation.csv"))
cat("Saved target_recommendation.csv:", nrow(final), "recommended targets\n")

# ---- 6. Console summary ---------------------------------------------------------
cat("\n===== Evidence funnel (biology only, each layer costs candidates) =====\n")
cat("  1. non-silent variant in this cohort  :", nrow(integrated), "genes\n")
cat("  2. + variant switches the protein ON  :", sum(integrated$gain_of_function), "genes\n")
cat("  3. + reachable by a large molecule    :", nrow(final), "gene(s)\n")
cat("  expression-driven shortlist overlap   :",
    sum(candidates$symbol %in% final$symbol), "genes\n")

cat("\n---- Layer 2 how each gene was settled (variant calls rolled up) ----\n")
print(integrated %>% select(symbol, n_variants, n_gof, n_lof, n_uncertain,
                            variant_function, evidence_level), n = 20)

cat("\n---- Not part of the funnel: what the same data looks like for the other modality ----\n")
small_mol <- integrated %>% filter(gain_of_function, !reachable_by_large_molecule)
cat("Switched-on AND intracellular (= small-molecule route):",
    paste(small_mol$symbol, collapse = ", "), "\n")

cat("\n---- Not part of the funnel: drug-landscape facts, printed as precedent only ----\n")
print(integrated %>% filter(gain_of_function) %>%
        left_join(precedent %>% select(symbol, approved_drug_status, targetable_alterations), by = "symbol") %>%
        select(symbol, subcellular_location, approved_drug_status, known_drug_class))

cat("\n===== TOP expression-driven candidates (druggable, up-regulated) =====\n")
print(head(candidates, 10))

cat("\n===== Mutated genes among the driver list =====\n")
print(mut_candidates, n = 20)

cat("\n===== Recommended target(s) after all three biology layers =====\n")
print(final)

cat("\n===== Variant-level calls behind layer 2 =====\n")
print(calls %>% count(symbol, functional_consequence) %>%
        tidyr::pivot_wider(names_from = functional_consequence, values_from = n,
                           values_fill = 0), n = 20)

cat("\n===== EGFR: the course target =====\n")
print(deg %>% filter(symbol == "EGFR") %>%
        select(symbol, baseMean, log2FoldChange, padj))
print(mut_candidates %>% filter(symbol == "EGFR"))

cat("\nEGFR is NOT among the expression-driven candidates. Here it is mutated in\n")
cat("2/14 tumours with mutation calls (the cohort has 15 tumours, one without a\n")
cat("MAF file); both are textbook activating events (exon 19 deletion, L858R),\n")
cat("and it sits on the cell surface. The expression shortlist and this funnel\n")
cat("share no gene at all: that gap is the lesson, not a bug.\n")
cat("KRAS and PIK3CA are switched on too, but they work inside the cell, so the\n")
cat("same data points a small-molecule programme at them instead. Which gene\n")
cat("wins depends on the modality you committed to, not on a ranking.\n")
cat("Next step (course 2): inspect the recommended target at protein level.\n")
